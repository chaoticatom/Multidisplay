// than importing either: title.js's font is missing several digits/
// punctuation a station name/genre string needs (4,5,6,7,&,',/,:,.), and
// weather/font.js's 3x5 font is legible for temperature readouts but too
// small to read comfortably scrolling across a 64px face. NOT the
// word-cascade engine's WC_FONT (effects-core.js) - that engine is out of
// scope for this port (see CLAUDE.md's pending task list); this is a
